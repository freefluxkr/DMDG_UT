# 실제 타이타닉 데이터를 URL로부터 로드하고 전처리합니다.
url = 'https://raw.githubusercontent.com/sehakflower/data/main/titanic.csv'
try:
    df = pd.read_csv(url, sep='\t')
    df['sex'] = df['Sex'].map({'male': 1, 'female': 0})
    df['pclass'] = df['Pclass']
    df['fare'] = df['Fare'].fillna(df['Fare'].median())
    df['title'] = df['Name'].str.extract(r' ([A-Za-z]+)\.', expand=False)
    title_mapping = {"Mr": 0, "Miss": 1, "Mrs": 2, "Master": 3}
    df['title'] = df['title'].map(title_mapping).fillna(4)
    df['age'] = df.groupby('title')['Age'].transform(lambda x: x.fillna(x.median()))
    df['age'] = df['age'].fillna(df['Age'].median())
    df['survived'] = df['Survived']
    
    X = df[['sex', 'pclass', 'fare', 'age', 'title']]
    y = df['survived']
    print("실제 타이타닉 데이터를 불러와 학습을 진행합니다!")
except Exception as e:
    print(f"실제 데이터 로드 실패 ({e}). 가상 임시 데이터를 사용합니다.")
