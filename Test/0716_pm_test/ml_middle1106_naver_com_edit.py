#2. 의사결정 트리 모델 생성 및 학습
# 그림과 같은 깊이(Depth)를 가지도록 max_depth를 3으로 제한하고,불순도 기준을 entropy로 설정합니다.
model = DecisionTreeClassifier(criterion='entropy', max_depth=3, random_state=42)
model.fit(X,y)
# 3. 트리 시각화 설정 및 그리기
